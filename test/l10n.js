    function enforceFont() {
        if (document.getElementById('l10n-global-font')) return;
        const st = document.createElement('style');
        st.id = 'l10n-global-font';
        st.textContent = `
            html, body {
                font-family: ${FONT_FAMILY} !important;
            }
            body *:not(svg):not(svg *) {
                font-family: ${FONT_FAMILY} !important;
            }
            input, textarea, button, select, option, label,
            div, span, p, h1, h2, h3, h4, h5, h6,
            a, li, ul, ol, pre, code, b, i, strong, em, small, td, th, table, tr, form {
                font-family: ${FONT_FAMILY} !important;
            }

            html.no-blur *,
            html.no-blur *::before,
            html.no-blur *::after {
                animation: none !important;
                transition: none !important;
                filter: none !important;
                backdrop-filter: none !important;
                -webkit-backdrop-filter: none !important;
            }
        `;
        document.head.appendChild(st);

        try {
            for (let s = 0; s < document.styleSheets.length; s++) {
                const sheet = document.styleSheets[s];
                if (sheet.id === 'l10n-global-font') continue;
                let rules;
                try { rules = sheet.cssRules; } catch(e) { continue; }
                if (!rules) continue;
                for (let r = 0; r < rules.length; r++) {
                    const rule = rules[r];
                    if (!rule.style) continue;
                    if (rule.style.fontFamily) {
                        rule.style.fontFamily = FONT_FAMILY;
                    }
                }
            }
        } catch(e) {}
    }

    function enforceIframeFont() {
        const iframes = document.querySelectorAll('iframe');
        iframes.forEach(function(ifr) {
            try {
                const doc = ifr.contentDocument;
                if (!doc) return;
                if (doc.getElementById('l10n-iframe-font')) return;
                const st = doc.createElement('style');
                st.id = 'l10n-iframe-font';
                st.textContent = `
                    html, body { font-family: ${FONT_FAMILY} !important; }
                    body *:not(svg):not(svg *) { font-family: ${FONT_FAMILY} !important; }
                `;
                doc.head && doc.head.appendChild(st);
            } catch(e) {}
        });
    }

